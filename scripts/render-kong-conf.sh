#!/usr/bin/env sh
set -eu

ROOT_DIR=$(CDPATH= cd -- "$(dirname -- "$0")/.." && pwd)
ENV_FILE=${1:-"$ROOT_DIR/.env"}
TEMPLATE_FILE="$ROOT_DIR/kong/kong.conf.template"
OUTPUT_FILE="$ROOT_DIR/kong/kong.conf"

if [ ! -f "$ENV_FILE" ]; then
  echo "Missing env file: $ENV_FILE" >&2
  exit 1
fi

set -a
. "$ENV_FILE"
set +a

: "${KONNECT_CONTROL_PLANE_ENDPOINT:?KONNECT_CONTROL_PLANE_ENDPOINT is required}"
: "${KONNECT_TELEMETRY_ENDPOINT:?KONNECT_TELEMETRY_ENDPOINT is required}"

KONNECT_CONTROL_PLANE_SERVER_NAME=${KONNECT_CONTROL_PLANE_SERVER_NAME:-$KONNECT_CONTROL_PLANE_ENDPOINT}
KONNECT_TELEMETRY_SERVER_NAME=${KONNECT_TELEMETRY_SERVER_NAME:-$KONNECT_TELEMETRY_ENDPOINT}

sed \
  -e "s|__KONNECT_CONTROL_PLANE_ENDPOINT__|$KONNECT_CONTROL_PLANE_ENDPOINT|g" \
  -e "s|__KONNECT_CONTROL_PLANE_SERVER_NAME__|$KONNECT_CONTROL_PLANE_SERVER_NAME|g" \
  -e "s|__KONNECT_TELEMETRY_ENDPOINT__|$KONNECT_TELEMETRY_ENDPOINT|g" \
  -e "s|__KONNECT_TELEMETRY_SERVER_NAME__|$KONNECT_TELEMETRY_SERVER_NAME|g" \
  "$TEMPLATE_FILE" > "$OUTPUT_FILE"

echo "Rendered $OUTPUT_FILE"
